import quopri


def decode_vcard(vcard):
    """
    Decodes a vCard to extract the name and phone number.
    :param vcard: The vCard string.
    :return: Tuple (decoded_name, phone_number).
    """
    lines = vcard.splitlines()
    name_line = next(line for line in lines if line.startswith("FN;"))
    phone_line = next(line for line in lines if line.startswith("TEL;"))

    # Extract and decode name
    encoded_name = name_line.split(":")[1]
    decoded_name = quopri.decodestring(encoded_name).decode("utf-8")

    # Extract phone number
    phone_number = phone_line.split(":")[1]

    return decoded_name, phone_number


def generate_contacts_from_vcards(vcards):
    """
    Decodes a list of vCards and produces a contact list.
    :param vcards: List of vCard strings.
    :return: List of tuples (name, phone).
    """
    return [decode_vcard(vcard) for vcard in vcards]


